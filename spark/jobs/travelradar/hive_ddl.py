"""Generates hive/tables.sql and hive/repair.sql from the Spark schemas.

    ./gen_hive_ddl.sh            # from spark/, after changing a parser

The cleaned tables' columns come from running each source's `parse` on an empty frame, so the Hive
DDL can never drift from what Spark writes (spark/tests/test_hive_ddl.py checks the committed files).
All tables are EXTERNAL: dropping them in Hive never deletes data on HDFS.
"""
from __future__ import annotations

import sys

from pyspark.sql import SparkSession
from pyspark.sql.types import StringType, StructField, StructType, TimestampType

from travelradar.sources import ALL

ROOT = "hdfs://namenode:9000/travelradar"
DATABASE = "travelradar"

RAW_COLUMNS = [("partition", "int"), ("offset", "bigint"), ("key", "string"), ("value", "string"),
               ("ingest_time", "timestamp")]
BATCH_RAW_COLUMNS = [("value", "string"), ("ingest_time", "timestamp")]

VIEW_COLUMNS = {
    "source_volume_daily": [("topic", "string"), ("records", "bigint"), ("bytes", "bigint"),
                            ("distinct_keys", "bigint"), ("first_ingest", "timestamp"),
                            ("last_ingest", "timestamp"), ("records_per_min", "double")],
    "quality_daily": [("table", "string"), ("column", "string"), ("check", "string"),
                      ("failed", "bigint"), ("total", "bigint"), ("rate", "double")],
    "consistency_daily": [("table", "string"), ("stream_rows", "bigint"), ("batch_rows", "bigint"),
                          ("diff_pct", "double")],
    "rail_delay_daily": [("train_category", "string"), ("arrivals", "bigint"),
                         ("mean_delay_min", "double"), ("std_delay_min", "double"),
                         ("p50_delay_min", "int"), ("p90_delay_min", "int"),
                         ("late_share", "double"), ("min_delay_min", "int"),
                         ("max_delay_min", "int")],
}

# batch backfills reuse the schema of the corresponding live table
BATCH_TABLES = {"train_stop_events_history": "train_stop_events",
                "weather_history": "weather_observations"}

FRAME = StructType([StructField("value", StringType()), StructField("ingest_time", TimestampType())])


def cleaned_columns(spark: SparkSession) -> dict[str, list[tuple[str, str]]]:
    empty = spark.createDataFrame([], FRAME)
    out = {}
    for source in ALL.values():
        schema = source.parse(empty).schema
        out[source.table] = [(f.name, f.dataType.simpleString()) for f in schema if f.name != "dt"]
    return out


def _table(name: str, columns, partitions, location: str, comment: str = "") -> str:
    cols = ",\n".join(f"  `{c}` {t.upper()}" for c, t in columns)
    parts = ", ".join(f"`{p}` STRING" for p in partitions)
    comment_sql = f"\nCOMMENT '{comment}'" if comment else ""
    return (f"DROP TABLE IF EXISTS {name};\n"
            f"CREATE EXTERNAL TABLE {name} (\n{cols}\n){comment_sql}\n"
            f"PARTITIONED BY ({parts})\nSTORED AS PARQUET\nLOCATION '{location}';\n")


def tables(spark: SparkSession) -> list[tuple[str, str]]:
    """(table name, DDL) for every table."""
    cleaned = cleaned_columns(spark)
    out = [("raw_events", _table("raw_events", RAW_COLUMNS, ["topic", "dt"], f"{ROOT}/raw/events",
                                 "bronze: every Kafka record as received; dt = ingest day"))]
    for source in ALL.values():
        out.append((source.table, _table(source.table, cleaned[source.table], ["dt"],
                                         f"{ROOT}/cleaned/{source.table}",
                                         source.description.replace("'", ""))))
    out.append(("batch_raw_events", _table("batch_raw_events", BATCH_RAW_COLUMNS, ["source", "dt"],
                                           f"{ROOT}/batch/raw", "bronze: raw history downloads")))
    for table, like in BATCH_TABLES.items():
        out.append((table, _table(table, cleaned[like], ["dt"], f"{ROOT}/batch/{table}",
                                  f"history backfill, same columns as {like}")))
    for view, cols in VIEW_COLUMNS.items():
        out.append((view, _table(view, cols, ["dt"], f"{ROOT}/views/{view}", "gold: batch view")))
    return out


def tables_sql(spark: SparkSession) -> str:
    header = ("-- GENERATED by spark/gen_hive_ddl.sh from the Spark schemas. Do not edit by hand.\n"
              "-- Executed by hive/start-hive.sh on every Hive start.\n\n"
              f"CREATE DATABASE IF NOT EXISTS {DATABASE};\nUSE {DATABASE};\n\n")
    return header + "\n".join(ddl for _, ddl in tables(spark))


def repair_sql(spark: SparkSession) -> str:
    lines = ["-- GENERATED by spark/gen_hive_ddl.sh. Registers new dt partitions written by Spark;",
             "-- run by hive/start-hive.sh every HIVE_SYNC_INTERVAL seconds.", f"USE {DATABASE};"]
    lines += [f"MSCK REPAIR TABLE {name} SYNC PARTITIONS;" for name, _ in tables(spark)]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    spark = SparkSession.builder.master("local[1]").config("spark.ui.enabled", "false").getOrCreate()
    spark.sparkContext.setLogLevel("ERROR")
    out_dir = sys.argv[1]
    with open(f"{out_dir}/tables.sql", "w") as f:
        f.write(tables_sql(spark))
    with open(f"{out_dir}/repair.sql", "w") as f:
        f.write(repair_sql(spark))
    print(f"wrote {out_dir}/tables.sql and {out_dir}/repair.sql")
    spark.stop()
